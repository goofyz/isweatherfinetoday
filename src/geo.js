function toRad(d) {
  return (d * Math.PI) / 180;
}

export function distanceKm(lat1, lng1, lat2, lng2) {
  const R = 6371;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) * Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

/** Ray-casting point-in-polygon; ring is [lat,lng] vertices (Geokit-compatible). */
export function pointInPeakPolygon(lat, lng) {
  const poly = PEAK_POLYGON;
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [yi, xi] = poly[i];
    const [yj, xj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / (yj - yi + 1e-12) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

export function sortStationsByDistance(stations, lat, lng) {
  return [...stations].sort(
    (a, b) =>
      distanceKm(lat, lng, Number(a.lat), Number(a.lng)) -
      distanceKm(lat, lng, Number(b.lat), Number(b.lng)),
  );
}
